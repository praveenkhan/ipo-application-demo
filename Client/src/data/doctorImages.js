/**
 * Checks if a doctor's name indicates a female practitioner
 */
export function isFemaleDoctor(name = "") {
  const clean = name.toLowerCase().replace(/dr\.?\s*/g, "").trim();
  return femaleNameKeywords.some((fn) => clean.includes(fn));
}

/**
 * Resolves an authentic, high-quality doctor photo based on name & gender
 */
export function getDoctorImage(doctor) {
  if (!doctor) return maleDoctorAvatars[0];

  const docName = (doctor.name || "").trim();

  // 1. Direct portrait match by exact name
  if (doctorPortraitsByName[docName]) {
    return doctorPortraitsByName[docName];
  }

  // 2. Check if normalized name matches (e.g. without extra spacing or punctuation)
  const normalizedKey = Object.keys(doctorPortraitsByName).find(
    (key) => key.toLowerCase().replace(/[\s.]/g, "") === docName.toLowerCase().replace(/[\s.]/g, "")
  );
  if (normalizedKey) {
    return doctorPortraitsByName[normalizedKey];
  }

  // 3. If doctor already has a custom uploaded real image (not a ui-avatars placeholder)
  if (
    doctor.image &&
    !doctor.image.includes("ui-avatars.com") &&
    !doctor.image.includes("placeholder")
  ) {
    return doctor.image;
  }

  // 4. Gender-aware fallback based on name hash
  const isFemale = isFemaleDoctor(docName);
  const avatarList = isFemale ? femaleDoctorAvatars : maleDoctorAvatars;
  
  // Deterministic index from name string
  let hash = 0;
  for (let i = 0; i < docName.length; i++) {
    hash = (hash << 5) - hash + docName.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % avatarList.length;

  return avatarList[index];
}

